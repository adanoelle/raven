#!/usr/bin/env bash
# Compile the spike's shaders to SPIR-V (Vulkan), MSL (Metal) and DXIL
# (Direct3D 12), and write each as a C header next to the source.
#
# Needs the shadercross CLI from SDL_shadercross:
#   nix shell nixpkgs#sdl3-shadercross -c tools/shader_spike/shaders/build.sh
#
# The headers are committed, so building the spike does not need this.

set -euo pipefail
cd "$(dirname "$0")"

make_header() {
    local file="$1"
    local name
    name="$(echo "$file" | tr '.-' '__')"
    {
        echo "// Generated by build.sh from ${file%.*}.hlsl. Do not edit."
        echo "static const unsigned char ${name}[] = {"
        xxd -i <"$file"
        echo "};"
    } >"$file.h"
}

for source in *.hlsl; do
    base="${source%.hlsl}"
    for format in spv msl dxil; do
        if shadercross "$source" -o "$base.$format"; then
            make_header "$base.$format"
            rm -f "$base.$format"
        else
            echo "warning: could not build $base.$format" >&2
            rm -f "$base.$format"
        fi
    done
done
