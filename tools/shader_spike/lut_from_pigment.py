#!/usr/bin/env python3
"""Turn saved Pigment build_palette output into lookup tables for the spike.

    python3 tools/shader_spike/lut_from_pigment.py

Reads palette/tables.json and the build_palette JSON files it names, and
writes pigment_lut.h next to this script. The header is committed, so
building the spike needs neither Python nor Pigment.

A first sketch of the table export Pigment would need (pigment issue 38).
What build_palette does not say, and this script therefore takes from
tables.json or assumes:

- Ramp order and variant order. The spike addresses ramps and variants by
  number; build_palette returns them in the order they were given. The
  manifest states the order the spike expects and the script fails when a
  build disagrees, by name.
- Which step the art sits on ("base"). A ramp has no marked local colour.
- How far the light and the ambient shift move ("zones", "ambient"), which
  depend on the ramp length.
- That every ramp has the same number of steps. The table is a rectangle;
  the script fails on ragged ramps instead of padding them.
- Rows that are the same in every variant ("fixed"). Pigment applies a
  variant's light to every ramp, so such rows come from a second build
  with no light.
- Colours are sRGB bytes, used as they are. Nothing is said about colour
  space in the JSON.
"""

import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
PALETTE_DIR = HERE / "palette"
OUT = HERE / "pigment_lut.h"


def fail(message):
    sys.exit(f"lut_from_pigment: {message}")


def load_build(name):
    with open(PALETTE_DIR / name, encoding="utf-8") as f:
        return json.load(f)


def rgb(hex_colour, where):
    text = hex_colour.lstrip("#")
    if len(text) != 6:
        fail(f"{where}: '{hex_colour}' is not a #rrggbb colour")
    return tuple(int(text[i : i + 2], 16) for i in (0, 2, 4))


def ramps_of(variant, ramp_names, where):
    """The variant's ramps as {name: [hex, ...]}, checked against the order."""
    got = [r["name"] for r in variant["ramps"]]
    if got != ramp_names:
        fail(f"{where}: ramps are {got}, the spike expects {ramp_names}")
    return {r["name"]: r["colors"] for r in variant["ramps"]}


def build_table(spec, ramp_names, variant_names):
    name = spec["name"]
    build = load_build(spec["build"])
    got_variants = [v["variant"] for v in build["variants"]]
    if got_variants != variant_names:
        fail(f"{name}: variants are {got_variants}, the spike expects {variant_names}")

    fixed_rows = {}
    if "fixed" in spec:
        fixed_build = load_build(spec["fixed"]["build"])
        if len(fixed_build["variants"]) != 1:
            fail(f"{name}: the build for fixed ramps must have exactly one variant")
        source = ramps_of(fixed_build["variants"][0], ramp_names, f"{name} (fixed)")
        fixed_rows = {ramp: source[ramp] for ramp in spec["fixed"]["ramps"]}

    rows = []
    for variant in build["variants"]:
        where = f"{name}, {variant['variant']}"
        ramps = ramps_of(variant, ramp_names, where)
        for ramp in ramp_names:
            rows.append((f"{variant['variant']}: {ramp}", fixed_rows.get(ramp, ramps[ramp])))

    steps = len(rows[0][1])
    for label, colours in rows:
        if len(colours) != steps:
            fail(f"{name}: '{label}' has {len(colours)} steps, the first ramp has {steps}")
    if not 0 <= spec["base"] < steps:
        fail(f"{name}: base step {spec['base']} is outside a ramp of {steps}")
    return {
        "name": name,
        "steps": steps,
        "base": spec["base"],
        "zones": spec["zones"],
        "ambient": spec["ambient"],
        "rows": [(label, [rgb(c, f"{name}, {label}") for c in colours]) for label, colours in rows],
    }


def emit(tables, ramp_count, variant_count):
    out = [
        "// Generated by lut_from_pigment.py from palette/tables.json. Do not edit.",
        "#pragma once",
        "",
        "/// A lookup table built from Pigment's build_palette output.",
        "struct PigmentTable {",
        "    const char* name;",
        "    int steps;   ///< Swatches per ramp: the table's width.",
        "    int base;    ///< The step the placeholder art sits on.",
        "    int zones;   ///< Steps the check's main light adds at its centre.",
        "    int ambient; ///< Ambient shift the check's main light case uses.",
        "    const unsigned char* rgb; ///< steps * ramps * variants colours, row by row.",
        "};",
        "",
        f"inline constexpr int PIGMENT_RAMPS = {ramp_count};",
        f"inline constexpr int PIGMENT_VARIANTS = {variant_count};",
        "",
    ]
    for index, table in enumerate(tables):
        out.append(f"inline constexpr unsigned char PIGMENT_RGB_{index}[] = {{")
        for label, colours in table["rows"]:
            cells = " ".join(f"{r},{g},{b}," for r, g, b in colours)
            out.append(f"    {cells} // {label}")
        out.append("};")
        out.append("")
    out.append("inline constexpr PigmentTable PIGMENT_TABLES[] = {")
    for index, table in enumerate(tables):
        out.append(
            f'    {{"{table["name"]}", {table["steps"]}, {table["base"]}, {table["zones"]}, '
            f'{table["ambient"]}, PIGMENT_RGB_{index}}},'
        )
    out.append("};")
    out.append("")
    return "\n".join(out)


def main():
    with open(PALETTE_DIR / "tables.json", encoding="utf-8") as f:
        manifest = json.load(f)
    ramp_names = manifest["ramps"]
    variant_names = manifest["variants"]
    tables = [build_table(spec, ramp_names, variant_names) for spec in manifest["tables"]]
    OUT.write_text(emit(tables, len(ramp_names), len(variant_names)), encoding="utf-8")
    for table in tables:
        print(f"{table['name']}: {table['steps']} steps, art on step {table['base']}")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
