#!/usr/bin/env python3
"""Encode an existing tileset as (ramp, step) values for the spike.

    python3 tools/shader_spike/art_from_tileset.py

Reads palette/dungeon-ramps.json, the tileset PNG and the LDtk map it names,
and writes dungeon_art.h: a lookup table, the tileset as index values, and
the map's rooms as tile numbers. Needs Pillow to read the PNG. The header is
committed, so building the spike needs neither.

The tileset's own colours are kept exactly, so the art looks as drawn when
nothing shifts it. Each material's ramp is those colours with generated
steps added below and above (from Pigment's fit_ramp) for light to move
into. A colour in the tileset that is in no ramp stops the script.

Limits: one tile layer, no flipped tiles, one environment (both variant
rows of the table are the same).
"""

import json
import sys
from pathlib import Path

from PIL import Image

HERE = Path(__file__).resolve().parent
PALETTE_DIR = HERE / "palette"
OUT = HERE / "dungeon_art.h"


def fail(message):
    sys.exit(f"art_from_tileset: {message}")


def rgb(hex_colour):
    text = hex_colour.lstrip("#")
    return tuple(int(text[i : i + 2], 16) for i in (0, 2, 4))


def main():
    spec = json.loads((PALETTE_DIR / "dungeon-ramps.json").read_text(encoding="utf-8"))
    tile = spec["tile"]

    # The table's rows, in the order the spike's ramp numbers expect.
    actors = spec["actors"]
    build = json.loads((PALETTE_DIR / actors["build"]).read_text(encoding="utf-8"))
    variant = next(v for v in build["variants"] if v["variant"] == actors["variant"])
    actor_rows = {r["name"]: r["colors"] for r in variant["ramps"] if r["name"] in actors["ramps"]}

    rows = []
    colour_to_index = {}
    for number, name in enumerate(spec["rows"]):
        if name in actor_rows:
            rows.append((name, actor_rows[name]))
            continue
        ramp = spec["ramps"][name]
        colours = list(ramp["fitted"])
        for offset, colour in enumerate(ramp["art"]):
            step = ramp["art_first_step"] + offset
            colours[step] = colour
            if rgb(colour) in colour_to_index:
                fail(f"{colour} is in two ramps; it cannot say which one a pixel belongs to")
            colour_to_index[rgb(colour)] = (number, step)
        rows.append((name, colours))
    steps = len(rows[0][1])
    if any(len(colours) != steps for _, colours in rows):
        fail("the ramps do not all have the same number of steps")

    # The tileset, pixel by pixel.
    sheet = Image.open(PALETTE_DIR / spec["tileset"]).convert("RGBA")
    indices = []
    unmatched = {}
    for y in range(sheet.height):
        for x in range(sheet.width):
            r, g, b, a = sheet.getpixel((x, y))
            if a != 255:
                fail(f"pixel {x},{y} is not opaque; the index pass has no translucency")
            index = colour_to_index.get((r, g, b))
            if index is None:
                unmatched[(r, g, b)] = unmatched.get((r, g, b), 0) + 1
                index = (0, 0)
            indices.append(index)
    if unmatched:
        listing = ", ".join(f"#{r:02x}{g:02x}{b:02x} ({n} px)" for (r, g, b), n in unmatched.items())
        fail(f"colours in the tileset that are in no ramp: {listing}")

    # The rooms.
    ldtk = json.loads((PALETTE_DIR / spec["map"]).read_text(encoding="utf-8"))
    rooms = []
    for level in ldtk["levels"]:
        layer = next(l for l in level["layerInstances"] if l["__type"] == "Tiles")
        width, height = layer["__cWid"], layer["__cHei"]
        grid = [0] * (width * height)
        for placed in layer["gridTiles"]:
            if placed["f"] != 0:
                fail(f"{level['identifier']}: flipped tiles are not handled")
            if placed["src"][1] != 0:
                fail(f"{level['identifier']}: the tileset is expected to be one row of tiles")
            grid[(placed["px"][1] // tile) * width + placed["px"][0] // tile] = placed["src"][0] // tile
        rooms.append((level["identifier"], width, height, grid))
    width, height = rooms[0][1], rooms[0][2]
    if any((w, h) != (width, height) for _, w, h, _ in rooms):
        fail("the rooms are not all the same size")

    out = [
        "// Generated by art_from_tileset.py from palette/dungeon-ramps.json. Do not edit.",
        "#pragma once",
        "",
        '#include "pigment_lut.h"',
        "",
        "inline constexpr unsigned char DUNGEON_RGB[] = {",
    ]
    for _ in range(2):  # the same rows for both variants: one environment
        for name, colours in rows:
            cells = " ".join("{},{},{},".format(*rgb(c)) for c in colours)
            out.append(f"    {cells} // {name}")
    out += [
        "};",
        "",
        f'inline constexpr PigmentTable DUNGEON_TABLE = {{"dungeon", {steps}, {spec["base"]}, '
        f'{spec["zones"]}, {spec["ambient"]}, DUNGEON_RGB}};',
        "",
        f"inline constexpr int DUNGEON_SHEET_W = {sheet.width};",
        f"inline constexpr int DUNGEON_SHEET_H = {sheet.height};",
        "/// The tileset as (ramp, step) pairs, row by row.",
        "inline constexpr unsigned char DUNGEON_SHEET[] = {",
    ]
    for y in range(sheet.height):
        line = " ".join(f"{r},{s}," for r, s in indices[y * sheet.width : (y + 1) * sheet.width])
        out.append(f"    {line}")
    out += [
        "};",
        "",
        f"inline constexpr int DUNGEON_ROOMS = {len(rooms)};",
        f"inline constexpr int DUNGEON_ROOM_W = {width};",
        f"inline constexpr int DUNGEON_ROOM_H = {height};",
        "inline constexpr const char* DUNGEON_ROOM_NAMES[] = {"
        + ", ".join(f'"{name}"' for name, _, _, _ in rooms)
        + "};",
        "/// Tile numbers, room after room, row by row.",
        "inline constexpr unsigned char DUNGEON_ROOM_TILES[] = {",
    ]
    for name, _, _, grid in rooms:
        out.append(f"    // {name}")
        for y in range(height):
            out.append("    " + ",".join(str(t) for t in grid[y * width : (y + 1) * width]) + ",")
    out += ["};", ""]
    OUT.write_text("\n".join(out), encoding="utf-8")
    print(f"{len(colour_to_index)} art colours in {len(spec['ramps'])} ramps, {steps} steps")
    print(f"{len(rooms)} rooms of {width}x{height} tiles: " + ", ".join(r[0] for r in rooms))
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
