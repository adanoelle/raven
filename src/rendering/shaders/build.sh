#!/usr/bin/env bash
# Compile the shaders here to SPIR-V (Vulkan), MSL (Metal) and DXIL
# (Direct3D 12), and write each as a C header next to the source.
#
#   just shaders          compile, with the pinned shadercross
#   just shaders-check    fail if the committed headers are out of date
#
# Both run this script in the flake's `shaders` shell, so every machine
# uses the same shadercross and writes the same bytes. The headers are
# committed: building the game does not need this script or its tools.
#
# Any failure stops the script. A header is only replaced once all of
# them have compiled, so a failed run leaves the tree as it was.

set -euo pipefail
cd "$(dirname "$0")"

for tool in shadercross xxd; do
    if ! command -v "$tool" >/dev/null; then
        echo "build.sh: '$tool' not found; run this through 'just shaders'" >&2
        exit 1
    fi
done

work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

headers=()
for source in *.hlsl; do
    base="${source%.hlsl}"
    for format in spv msl dxil; do
        compiled="$base.$format"
        shadercross "$source" -o "$work/$compiled"
        if [[ ! -s "$work/$compiled" ]]; then
            echo "build.sh: shadercross wrote nothing for $compiled" >&2
            exit 1
        fi
        {
            echo "// Generated by build.sh from $source. Do not edit."
            echo "static const unsigned char $(echo "$compiled" | tr '.-' '__')[] = {"
            xxd -i <"$work/$compiled"
            echo "};"
        } >"$work/$compiled.h"
        headers+=("$compiled.h")
    done
done

for header in "${headers[@]}"; do
    mv "$work/$header" "$header"
done
echo "build.sh: wrote ${#headers[@]} headers"
